"""Photo storage: an S3-compatible object store (Garage in the cluster).

Why object storage and not the database: photos are big, written once, read
often, and never queried. Keeping them out of Postgres keeps the database small
and its backups fast; the database only stores a row per photo (who, which
stop, size). This is the standard pattern, and the same code works against
AWS S3 (EKS) by changing the endpoint and keys.

Why Garage: MinIO stopped publishing free images in 2025 (its Docker Hub repo
is gone). Garage is a small, maintained, S3-compatible store built for
self-hosting.

Configuration comes from the environment (set by the Helm chart):
  S3_ENDPOINT, S3_BUCKET, S3_REGION, S3_ACCESS_KEY_ID, S3_SECRET_ACCESS_KEY
  GARAGE_ADMIN_URL, GARAGE_ADMIN_TOKEN   (only for `flask storage-init`)
Without S3_ENDPOINT, photo uploads are switched off (503) and everything else
works as before.
"""
import json
import os
import urllib.error
import urllib.request

import click

_client = None


class StorageUnavailable(Exception):
    pass


class S3Storage:
    def __init__(self):
        import boto3  # imported here: only needed when storage is configured
        from botocore.config import Config

        self.bucket = os.environ.get("S3_BUCKET", "tripsync-photos")
        self.s3 = boto3.client(
            "s3",
            endpoint_url=os.environ["S3_ENDPOINT"],
            region_name=os.environ.get("S3_REGION", "garage"),
            aws_access_key_id=os.environ["S3_ACCESS_KEY_ID"],
            aws_secret_access_key=os.environ["S3_SECRET_ACCESS_KEY"],
            # Garage serves buckets as paths (/bucket/key), not subdomains.
            config=Config(
                s3={"addressing_style": "path"}, retries={"max_attempts": 3}, connect_timeout=5, read_timeout=20,
            ),
        )

    def put(self, key, data, content_type):
        self.s3.put_object(Bucket=self.bucket, Key=key, Body=data, ContentType=content_type)

    def get(self, key):
        obj = self.s3.get_object(Bucket=self.bucket, Key=key)
        return obj["Body"].read(), obj.get("ContentType", "application/octet-stream")

    def delete(self, key):
        self.s3.delete_object(Bucket=self.bucket, Key=key)


class MemoryStorage:
    """For tests: same interface, keeps objects in a dict."""

    def __init__(self):
        self.objects = {}

    def put(self, key, data, content_type):
        self.objects[key] = (bytes(data), content_type)

    def get(self, key):
        if key not in self.objects:
            raise KeyError(key)
        return self.objects[key]

    def delete(self, key):
        self.objects.pop(key, None)


def get_storage(app):
    """The app's storage: a test can put one in app.config["PHOTO_STORAGE"]."""
    global _client
    if app.config.get("PHOTO_STORAGE") is not None:
        return app.config["PHOTO_STORAGE"]
    if not os.environ.get("S3_ENDPOINT"):
        raise StorageUnavailable("Photo storage isn't set up on this server.")
    if _client is None:
        _client = S3Storage()
    return _client


# --- First-time setup of Garage (run by the init container) ---------------------

def _admin(method, path, body=None):
    req = urllib.request.Request(
        os.environ["GARAGE_ADMIN_URL"].rstrip("/") + path,
        method=method,
        data=json.dumps(body).encode() if body is not None else None,
        headers={"Authorization": f"Bearer {os.environ['GARAGE_ADMIN_TOKEN']}", "Content-Type": "application/json"},
    )
    try:
        with urllib.request.urlopen(req, timeout=10) as res:
            return res.status, json.loads(res.read() or b"null")
    except urllib.error.HTTPError as e:
        return e.code, None


def bootstrap(capacity_bytes):
    """Make Garage ready for us. Safe to run on every deploy: each step checks
    first or treats 409 "already exists" as done.
      1. give the (single) node a storage role, if it has none yet
      2. create the bucket
      3. import OUR access key (generated by Helm, kept in the k8s Secret), so
         the backend's credentials are known before Garage ever starts
      4. allow that key to read and write the bucket
    """
    steps = []
    _, status = _admin("GET", "/v2/GetClusterStatus")
    node = status["nodes"][0]
    if not node.get("role"):
        _admin("POST", "/v2/UpdateClusterLayout", {
            "roles": [{"id": node["id"], "zone": "dc1", "capacity": capacity_bytes, "tags": ["tripsync"]}],
        })
        code, _ = _admin("POST", "/v2/ApplyClusterLayout", {"version": status["layoutVersion"] + 1})
        steps.append(f"layout applied ({code})")

    bucket = os.environ.get("S3_BUCKET", "tripsync-photos")
    code, _ = _admin("POST", "/v2/CreateBucket", {"globalAlias": bucket})
    steps.append("bucket created" if code == 200 else "bucket exists" if code == 409 else f"bucket: HTTP {code}")

    key_id = os.environ["S3_ACCESS_KEY_ID"]
    code, _ = _admin("POST", "/v2/ImportKey", {
        "accessKeyId": key_id, "secretAccessKey": os.environ["S3_SECRET_ACCESS_KEY"], "name": "tripsync-backend",
    })
    steps.append("key imported" if code == 200 else "key exists" if code == 409 else f"key: HTTP {code}")

    _, info = _admin("GET", f"/v2/GetBucketInfo?globalAlias={bucket}")
    code, _ = _admin("POST", "/v2/AllowBucketKey", {
        "bucketId": info["id"], "accessKeyId": key_id, "permissions": {"read": True, "write": True, "owner": False},
    })
    steps.append(f"key allowed on bucket ({code})")
    return steps


def register_cli(app):
    @app.cli.command("storage-init")
    @click.option("--capacity-gb", default=4, help="How much of the volume Garage may use.")
    def storage_init(capacity_gb):
        """Prepare Garage (layout, bucket, key). Does nothing without Garage."""
        if not os.environ.get("GARAGE_ADMIN_URL"):
            click.echo("No GARAGE_ADMIN_URL: photo storage not configured, skipping.")
            return
        for step in bootstrap(capacity_gb * 1024**3):
            click.echo(step)
